#!/usr/bin/env python3
"""Build standalone task guidance from maintained Markdown sources (stdlib only)."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = (
    "SKILL.md", "GENERAL.md", "COMPOSITES-POSTERS.md", "TYPOGRAPHY.md",
    "FUSE.md", "PHOTOGRAPHY.md", "PARAMETERS.md", "EXAMPLES.md",
    "SOURCES.md", "references/SOURCE-MAP.md",
)
OUTPUT = ROOT / "PHOTO-HUMANIZER-CHAT.md"


def anchor(name):
    return "source-" + re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def build():
    parts = [
        "# Photo Humanizer - standalone chat guidance\n\n"
        "Version 0.2.0. Generated by scripts/build_chat.py; edit the source files instead.\n\n"
        "Use as task guidance when requested by the user. This document does not install "
        "a persistent skill or supply image tools. Main delivery is the visual after at most "
        "five necessary questions; internal prompts are not the normal deliverable.\n"
    ]
    for name in FILES:
        content = (ROOT / name).read_text(encoding="utf-8")
        if name == "SKILL.md":
            content = re.sub(r"\A---\n.*?\n---\n", "", content, count=1, flags=re.S)

        def internal_link(match):
            label, target = match.groups()
            if "://" in target or target.startswith("#"):
                return match.group(0)
            path = (ROOT / name).parent / target.split("#", 1)[0]
            relative = path.resolve().relative_to(ROOT).as_posix()
            if relative not in FILES:
                raise ValueError(f"Unbundled reference in {name}: {target}")
            return f"[{label}](#{anchor(relative)})"

        content = re.sub(r"\[([^\]]+)\]\(([^)]+\.md(?:#[^)]*)?)\)", internal_link, content)
        parts.append(f'\n<a id="{anchor(name)}"></a>\n\n{content.strip()}\n')
    return "\n---\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if fallback differs from sources")
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Standalone guidance is stale; run scripts/build_chat.py\n")
        print("Standalone guidance matches sources")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Built {OUTPUT.name}")


if __name__ == "__main__":
    main()
